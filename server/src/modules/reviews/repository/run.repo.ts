/** Create an agent_runs row in `running` state; returns its id (= the runId). */
export async function createAgentRun(
  db: DbOrTx,
  values: {
    workspaceId: string;
    agentId: string | null;
    prId: string;
    provider: string | null;
    model: string | null;
  },
): Promise<string> {
  const [row] = await db
    .insert(t.agentRuns)
    .values({
      workspaceId: values.workspaceId,
      agentId: values.agentId,
      prId: values.prId,
      provider: values.provider,
      model: values.model,
      status: 'running',
      source: 'local',
    })
    .returning({ id: t.agentRuns.id });
  return row!.id;
}

export async function completeAgentRun(
  db: DbOrTx,
  runId: string,
  values: RunCompletion,
): Promise<void> {
  await db
    .update(t.agentRuns)
    .set({
      status: values.status,
      durationMs: values.durationMs,
      tokensIn: values.tokensIn,
      tokensOut: values.tokensOut,
      costUsd: values.costUsd ?? null,
      findingsCount: values.findingsCount,
      grounding: values.grounding,
      score: values.score ?? null,
      blockers: values.blockers ?? null,
      error: values.error ?? null,
    })
    .where(eq(t.agentRuns.id, runId));
}

/**
 * Total cost (USD) per PR over its COMPLETED runs — the PR list's COST column.
 * PRs with no costed `done` run are absent from the map (→ shown as "—").
 */
export async function costByPull(db: DbOrTx, prIds: string[]): Promise<Map<string, number>> {
  const out = new Map<string, number>();
  if (prIds.length === 0) return out;
  const rows = await db
    .select({ prId: t.agentRuns.prId, total: sql<number>`sum(${t.agentRuns.costUsd})`.mapWith(Number) })
    .from(t.agentRuns)
    .where(
      and(
        inArray(t.agentRuns.prId, prIds),
        eq(t.agentRuns.status, 'done'),
        isNotNull(t.agentRuns.costUsd),
      ),
    )
    .groupBy(t.agentRuns.prId);
  for (const r of rows) if (r.prId) out.set(r.prId, r.total);
  return out;
}

/** Persist the WHOLE run log as ONE document. PK = runId → agent_runs. */
export async function saveRunTrace(db: DbOrTx, runId: string, trace: RunTrace): Promise<void> {
  await db
    .insert(t.runTraces)
    .values({ runId, trace })
    .onConflictDoUpdate({ target: t.runTraces.runId, set: { trace } });
}

export async function getRunTrace(db: DbOrTx, runId: string): Promise<RunTrace | undefined> {
  const [row] = await db.select().from(t.runTraces).where(eq(t.runTraces.runId, runId));
  return row ? (row.trace as RunTrace) : undefined;
}
